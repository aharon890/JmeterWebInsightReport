#!/usr/bin/env bash
# =============================================================================
#  Serve test-results/ over http, so a browser agent can open the reports.
#
#  THIS IS NOT A CONVENIENCE. The Claude Chrome extension refuses file:// URLs
#  outright — "Can't interact with browser-internal or unparseable URLs" — so a
#  generated report cannot be opened the way a human opens it. Without this
#  script every browser session rediscovers that and stalls.
#
#  Usage:
#      ./scripts/serve-reports.sh              # foreground, Ctrl-C to stop
#      ./scripts/serve-reports.sh --list       # print the URLs and exit
#      WIR_PORT=9000 ./scripts/serve-reports.sh
#
#  ---------------------------------------------------------------------------
#  ONE THING TO KNOW BEFORE YOU TRUST WHAT YOU SEE
#
#  E19 and E20 use the EXTERNAL-DATA path: the chart payload is a sibling .js
#  loaded with <script src>, chosen precisely because fetch() is CORS-blocked on
#  file://. Over http it loads by a route that does not exist for a real user
#  opening the file from disk. So a finding about a DEGRADED or MISSING payload
#  on those two must be re-checked over file:// in an ordinary browser before it
#  is believed. Everything else renders identically either way.
# =============================================================================
set -uo pipefail

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

PORT="${WIR_PORT:-8777}"
HOST="127.0.0.1"

# What each fixture is FOR. This is the mission catalogue's index: an explorer
# picking a report should not have to reverse-engineer which one shows what.
declare -a FIXTURES=(
    "EXAMPLE|the checked-in example — many samplers, client and server asserts (demo server data), a real failure"
    "E25|every rule state at once: PASS WARN FAIL OBSERVE DISABLED INVALID unmatched"
    "E02|the big one, and it declares NO asserts — the neutral/empty states"
    "E10|a gate that passes"
    "E11|a gate that fails"
    "E12|notes, markers and sampler notes all populated"
    "E19|EXTERNAL DATA — see the caveat in this script's header"
    "E05|20 samplers — table and legend behaviour under width pressure"
    "CMP|the Compare tab (needs generate-cmp-fixture.sh)"
)

print_urls() {
    echo ""
    echo "  Reports on http://$HOST:$PORT"
    echo ""
    local missing=0
    for entry in "${FIXTURES[@]}"; do
        local id="${entry%%|*}" desc="${entry#*|}"
        # Prefer <ID>-report.html: CMP also contains baseline.html, and a plain
        # alphabetical head -1 pointed the explorer at the baseline instead of the
        # comparison — the one report in that directory that is not the point.
        #
        # judged/ first: refresh-report-example.sh publishes the `jmeter -g -o` report it
        # writes there, the one that judges the server asserts. The listener's report
        # beside it is the interim one, Server tab NOT COLLECTED, and is not reportExample/.
        local html=""
        for candidate in "$RESULTS_DIR/$id/judged/web-insight-report.html" \
                         "$RESULTS_DIR/$id/$id-report.html" "$RESULTS_DIR/$id/web-insight-report.html"; do
            [[ -f "$candidate" ]] && { html="$candidate"; break; }
        done
        [[ -z "$html" ]] && html="$(ls "$RESULTS_DIR/$id"/*.html 2>/dev/null | head -1)"
        if [[ -n "$html" ]]; then
            printf '    http://%s:%s/%-40s %s\n' "$HOST" "$PORT" "${html#"$RESULTS_DIR"/}" "$desc"
        else
            printf '    %-52s %s\n' "($id not generated)" "$desc"
            missing=$((missing + 1))
        fi
    done
    echo ""
    if [[ $missing -gt 0 ]]; then
        echo "  Missing fixtures are generated by:"
        echo "    ./test-plans/scripts/run-all-tests.sh        (most)"
        echo "    ./test-plans/scripts/generate-cmp-fixture.sh (CMP)"
        echo "    ./scripts/refresh-report-example.sh          (EXAMPLE)"
        echo ""
    fi
}

if [[ ! -d "$RESULTS_DIR" ]]; then
    echo "ERROR: no test-results/ directory. Generate fixtures first:" >&2
    echo "  ./test-plans/scripts/run-all-tests.sh" >&2
    exit 1
fi

if [[ "${1:-}" == "--list" ]]; then
    print_urls
    exit 0
fi

require_python

# Bound to 127.0.0.1 on purpose: these are unreviewed generated artifacts that can
# contain response bodies captured from whatever was under test. They have no
# business being reachable from the network.
print_urls
echo "  Ctrl-C to stop."
echo ""
exec "$PYTHON" -m http.server "$PORT" --bind "$HOST" --directory "$RESULTS_DIR"
